#!/usr/bin/env python3
"""Bundle src/*.lua into a single self-contained Luau module at dist/deepluau.luau.

Relative `require("./X")` only works in some Luau runtimes (and not in Roblox),
so the bundle wraps every module in a lazy registry keyed by basename and rewrites
the requires. The bundled file `return`s the Obfuscator table.
"""
import os, re, sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(REPO, "src")

MODULES = [
    "Rng.lua", "Lexer.lua", "Parser.lua", "Generator.lua", "Scope.lua",
    "passes/Numbers.lua", "passes/Strings.lua", "passes/Flatten.lua",
    "Obfuscator.lua",
]

REQ = re.compile(r'require\(\s*"\.[^"]*?/?([A-Za-z_]+)"\s*\)')

def main():
    out = [
        "--!native",
        "-- DeepLuaU (bundled). Generated by tools/bundle.py -- do not edit by hand.",
        "-- Usage: local Obfuscator = require(path); Obfuscator.obfuscate(src, opts)",
        "local __mods = {}",
        "local __cache = {}",
        "local function __require(name)",
        "\tlocal c = __cache[name]",
        "\tif c ~= nil then return c end",
        "\tlocal m = __mods[name]()",
        "\t__cache[name] = m",
        "\treturn m",
        "end",
        "",
    ]
    for rel in MODULES:
        name = os.path.splitext(os.path.basename(rel))[0]
        with open(os.path.join(SRC, rel)) as f:
            body = f.read()
        body = REQ.sub(lambda m: '__require("%s")' % m.group(1), body)
        out.append('__mods["%s"] = function()' % name)
        out.append(body)
        out.append("end")
        out.append("")
    out.append('return __require("Obfuscator")')

    dist = os.path.join(REPO, "dist")
    os.makedirs(dist, exist_ok=True)
    target = os.path.join(dist, "deepluau.luau")
    with open(target, "w") as f:
        f.write("\n".join(out))
    print("wrote", target, "(%d modules)" % len(MODULES))

if __name__ == "__main__":
    main()
